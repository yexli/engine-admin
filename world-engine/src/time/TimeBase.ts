/* ============================================================
   时间基元（纯常量，零依赖）
   ------------------------------------------------------------
   这四个数值与宿主当前线上值完全一致（48 刻 = 1 日、12 月 × 30 日、
   16 岁起步），作为引擎的**默认历法**。宿主游戏可以在创建时钟时
   覆盖成自己的历法，但同一局世界内它们恒定。

   为什么常量独立成文件：寿命/年龄类换算要「出生刻」，出生刻要用
   一年的刻度数——状态模块若 import 时钟模块就成环。常量放这里
   两边都能用；换算**函数**归时钟（它是时间换算的唯一实现点）。
   ============================================================ */

/** 一日的刻度数（默认 48 刻 = 1 日；每时辰 4 刻）。时间换算的唯一来源。 */
export const CHEN_PER_DAY = 48;

/** 一年的日数（默认历法：12 月 × 30 日）。 */
export const DAYS_PER_YEAR = 360;

/** 一年的刻度数。寿命表与年龄换算都引它。 */
export const TICKS_PER_YEAR = CHEN_PER_DAY * DAYS_PER_YEAR;

/** 创角默认年龄（岁）。 */
export const START_AGE = 16;
